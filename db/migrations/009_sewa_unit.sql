-- ============================================================================
-- 009: unit sewa (seperti kontrak di Odoo Fleet) + untung rugi per trip & per unit
--
-- Unit yang disewa bulanan: biaya sewa jadi biaya per hari (sewa / jumlah hari bulan itu). Trip diambil dari job
-- dengan plat yang sama (atau vehicle_id). Hari trip = tanggal gate out s/d gate in (WIB); job tanpa gate = tanggal job.
-- Kalau satu hari dipakai beberapa job (rit dalam kota, atau hari pulang = hari berangkat lagi), sewa hari itu dibagi rata.
--   kontribusi trip = selling - cost job (uang jalan, sudah termasuk tol / makan / gaji driver)
--   untung trip     = kontribusi - sewa teralokasi
--   untung unit     = kontribusi trip bulan itu - sewa bulan itu (hari menganggur tetap dibayar)
-- Tagihan sewa bulanan (SWA/YYMM/NNNN) + pembayarannya dicatat terpisah dari invoice / pengajuan job.
-- (Nomor 008 dipesan untuk kas operasional.)
-- ============================================================================
create table vehicle_contract (
  id integer generated by default as identity primary key,
  vehicle_id integer not null references vehicle(id),
  partner_id integer references res_partner(id),          -- pemilik / yang menyewakan
  date_start date not null,
  date_end date,                                          -- kosong = masih berjalan
  monthly_rent numeric(15, 2) not null check (monthly_rent >= 0),
  other_monthly_cost numeric(15, 2) not null default 0 check (other_monthly_cost >= 0),   -- biaya tetap lain (asuransi, GPS)
  note text,
  created_by integer references app_user(id),
  created_at timestamptz not null default now(),
  check (date_end is null or date_end >= date_start)
);
create index vehicle_contract_vehicle_idx on vehicle_contract (vehicle_id);

create table vehicle_rent_bill (
  id integer generated by default as identity primary key,
  number text not null unique,                            -- SWA/YYMM/NNNN
  contract_id integer not null references vehicle_contract(id),
  period date not null,                                   -- tanggal 1 bulan sewa
  days integer not null,                                  -- hari sewa di bulan itu (prorata kalau mulai / selesai di tengah bulan)
  amount numeric(15, 2) not null check (amount > 0),
  due_date date,
  note text,
  state text not null default 'posted' check (state in ('posted', 'cancelled')),
  cancel_reason text,
  created_by integer references app_user(id),
  created_at timestamptz not null default now()
);
create unique index vehicle_rent_bill_once on vehicle_rent_bill (contract_id, period) where state = 'posted';

create table vehicle_rent_payment (
  id integer generated by default as identity primary key,
  bill_id integer not null references vehicle_rent_bill(id),
  pay_date date not null,
  amount numeric(15, 2) not null,                         -- minus = pembalik
  bank_account_id integer references res_bank_account(id),
  reversed_payment_id integer references vehicle_rent_payment(id),
  note text,
  created_by integer references app_user(id),
  created_at timestamptz not null default now()
);

create view v_vehicle_rent_bill as
select b.*, coalesce(p.paid, 0) as paid, case when b.state = 'cancelled' then 0 else b.amount - coalesce(p.paid, 0) end as residual
from vehicle_rent_bill b
left join (select bill_id, sum(amount) as paid from vehicle_rent_payment group by bill_id) p on p.bill_id = b.id;

-- biaya sewa per hari per unit, sampai akhir kontrak atau akhir bulan berjalan
create view v_vehicle_day as
select c.id as contract_id, c.vehicle_id, d::date as day,
       (c.monthly_rent + c.other_monthly_cost)
         / extract(day from date_trunc('month', d) + interval '1 month' - interval '1 day')::numeric as day_cost
from vehicle_contract c
cross join lateral generate_series(
  c.date_start,
  coalesce(c.date_end, (date_trunc('month', (now() at time zone 'Asia/Jakarta')) + interval '1 month' - interval '1 day')::date),
  interval '1 day') d;

-- job -> unit sewa (vehicle_id, atau plat yang sama tanpa melihat spasi / huruf besar)
create view v_vehicle_trip as
select j.id as job_id, v.id as vehicle_id,
       coalesce((j.gate_out_at at time zone 'Asia/Jakarta')::date, j.job_date) as day_from,
       greatest(coalesce((j.gate_out_at at time zone 'Asia/Jakarta')::date, j.job_date),
                coalesce((j.gate_in_at at time zone 'Asia/Jakarta')::date,
                         case when j.gate_out_at is not null then (now() at time zone 'Asia/Jakarta')::date end,
                         j.job_date)) as day_to,
       j.gate_out_at is not null and j.gate_in_at is null as masih_jalan,
       j.gate_out_at is null as tanpa_gate
from job j
join vehicle v on v.id = coalesce(j.vehicle_id,
  (select v2.id from vehicle v2 where upper(regexp_replace(v2.plate_number, '\s', '', 'g')) = upper(regexp_replace(j.plate_number, '\s', '', 'g')) limit 1))
where j.state <> 'cancelled' and exists (select 1 from vehicle_contract c where c.vehicle_id = v.id);

-- sewa teralokasi per trip: tiap hari dibagi rata ke job yang memakai unit di hari itu
create view v_vehicle_trip_cost as
with occ as (
  select t.job_id, t.vehicle_id, d::date as day
  from v_vehicle_trip t cross join lateral generate_series(t.day_from, t.day_to, interval '1 day') d
),
shared as (select vehicle_id, day, count(*) as n from occ group by vehicle_id, day)
select o.job_id, o.vehicle_id, count(*)::int as days, coalesce(sum(vd.day_cost / s.n), 0) as rent_cost
from occ o
join shared s on s.vehicle_id = o.vehicle_id and s.day = o.day
left join v_vehicle_day vd on vd.vehicle_id = o.vehicle_id and vd.day = o.day
group by o.job_id, o.vehicle_id;
