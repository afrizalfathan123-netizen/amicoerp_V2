-- ============================================================================
-- 013: job ekspor / impor (freight forwarding, nomor berakhiran FF).
-- (008 dicadangkan untuk 008_kas_operasional.sql yang belum digabung.)
--
-- - job.service_type = 'FORWARDING' = job ekspor / impor. Nomornya memakai urutan nomor yang SAMA dengan job domestik
--   bulan itu, ditambah akhiran FF (AMC/2610/0793FF), jadi satu nomor selalu satu job.
--   Muatan (FCL / LCL / UDARA) disimpan di job.truck_type, pelabuhan / bandara asal-tujuan di job.pol_id / pod_id (master lokasi).
-- - job_shipment: data pengiriman satu per job FF (arah, moda, shipper / consignee, barang, kapal / pesawat, jadwal, dokumen).
-- - job_container: daftar kontainer per job (bisa banyak).
-- - Jenis biaya baru untuk ekspor / impor: freight, THC, dokumen, bea cukai / PPJK, storage / demurrage, handling.
-- Tagihan dalam USD menyusul (tahap 2).
-- ============================================================================
create table job_shipment (
  job_id integer primary key references job(id) on delete cascade,
  direction text not null check (direction in ('EXPORT', 'IMPORT')),
  mode text not null check (mode in ('SEA', 'AIR')),
  shipper text,
  consignee text,
  notify_party text,
  commodity text,
  packages numeric(12, 2) check (packages is null or packages >= 0),
  package_unit text,                       -- CTN, PLT, PKG, ...
  gross_weight numeric(14, 3) check (gross_weight is null or gross_weight >= 0),   -- KGM
  volume numeric(14, 3) check (volume is null or volume >= 0),                     -- M3
  carrier text,                            -- pelayaran / maskapai
  vessel text,                             -- nama kapal / nomor penerbangan
  voyage text,
  etd date,
  eta date,
  mbl_number text,                         -- master B/L (laut) / MAWB (udara)
  hbl_number text,                         -- house B/L / HAWB
  aju_number text,                         -- nomor aju / PO
  customs_number text,                     -- PEB (ekspor) / PIB (impor)
  incoterm text,                           -- FOB, CIF, EXW, ...
  note text,
  check (eta is null or etd is null or eta >= etd)
);

create table job_container (
  id integer generated by default as identity primary key,
  job_id integer not null references job(id) on delete cascade,
  container_number text,                   -- boleh kosong dulu (belum dapat kontainer)
  size text not null check (size in ('20', '40', '40HC', '45')),
  seal_number text,
  note text
);
create index job_container_job_idx on job_container (job_id);
create unique index job_container_number_key on job_container (job_id, upper(container_number)) where container_number is not null;

alter table product drop constraint product_kind_check;
alter table product add constraint product_kind_check check (kind in ('TRUCKING', 'CALO', 'TOL', 'PARKIR', 'BONGKAR', 'LAINNYA', 'SELISIH',
  'FREIGHT', 'THC', 'DOKUMEN', 'BEA_CUKAI', 'STORAGE', 'HANDLING'));
insert into product (code, name, kind) values
  ('FREIGHT', 'Freight (laut / udara)', 'FREIGHT'),
  ('THC', 'THC (terminal handling)', 'THC'),
  ('DOKUMEN', 'Biaya dokumen', 'DOKUMEN'),
  ('BEA_CUKAI', 'Bea cukai / PPJK', 'BEA_CUKAI'),
  ('STORAGE', 'Storage / demurrage', 'STORAGE'),
  ('HANDLING', 'Handling', 'HANDLING');

-- job FF lama (dari impor JOB REG, nomor berakhiran FF) ditandai sebagai ekspor / impor
update job set service_type = 'FORWARDING' where job_number ~* 'FF$' and service_type <> 'FORWARDING';
