-- ============================================================================
-- 012: keamanan login + pengajuan uang kembali oleh operasional.
-- (008 dicadangkan untuk 008_kas_operasional.sql yang belum digabung.)
--
-- Login:
--   - must_change_password: akun baru / password direset ADMIN wajib ganti password saat login pertama.
--   - app_session.token sekarang berisi HASH sha256 dari token di cookie (bocor database = sesi tetap tidak bisa dipakai).
--     Sesi yang sudah ada di-hash di sini, jadi user tidak perlu login ulang.
--   - last_seen_at: sesi habis kalau tidak dipakai beberapa jam (SESSION_IDLE_HOURS, bawaan 8).
--   - login_event: catatan login berhasil / gagal, logout, keluar dari semua perangkat (IP & browser).
-- Uang kembali dari vendor: OPERATIONAL mengajukan (vendor_refund_request), FINANCE mengonfirmasi setelah uangnya masuk
-- (baru saat itu nota kredit NKV + uang kembali RFD dibuat) atau menolak.
-- ============================================================================
alter table app_user add column must_change_password boolean not null default false;
alter table app_user add column password_changed_at timestamptz;

alter table app_session add column id integer generated by default as identity;
alter table app_session add constraint app_session_id_key unique (id);
alter table app_session add column last_seen_at timestamptz not null default now();
alter table app_session add column ip text;
alter table app_session add column user_agent text;
update app_session set token = encode(sha256(convert_to(token, 'UTF8')), 'hex');

create table login_event (
  id integer generated by default as identity primary key,
  at timestamptz not null default now(),
  username text,
  user_id integer references app_user(id) on delete set null,
  event text not null check (event in ('LOGIN', 'LOGIN_GAGAL', 'LOGOUT', 'KELUAR_SEMUA', 'SESI_DIHAPUS', 'GANTI_PASSWORD')),
  note text,
  ip text,
  user_agent text
);
create index login_event_at_idx on login_event (at desc);
create index login_event_user_idx on login_event (user_id, at desc);

create table vendor_refund_request (
  id integer generated by default as identity primary key,
  job_id integer not null references job(id),
  move_line_id integer not null references account_move_line(id),   -- baris pengajuan vendor yang uangnya kembali
  amount numeric(15, 2) not null check (amount > 0),
  after text not null check (after in ('CANCEL_JOB', 'REDUCE_COST', 'KEEP_COST')),
  reason text not null,
  state text not null default 'PENDING' check (state in ('PENDING', 'CONFIRMED', 'REJECTED', 'CANCELLED')),
  requested_by integer references app_user(id),
  requested_at timestamptz not null default now(),
  decided_by integer references app_user(id),
  decided_at timestamptz,
  decision_note text,
  credit_note_id integer references account_move(id)                 -- nota kredit NKV saat dikonfirmasi
);
create index vendor_refund_request_job_idx on vendor_refund_request (job_id);
create index vendor_refund_request_pending_idx on vendor_refund_request (requested_at) where state = 'PENDING';
