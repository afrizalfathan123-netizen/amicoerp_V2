-- ============================================================================
-- ERP AMICO v2: skema dasar. Model AMICO Lite (ala Odoo / ERPNext) + kebutuhan AMICO.
--
--   AKSES       app_user, app_session, audit_log
--   PENGATURAN  app_setting, ir_sequence
--   MASTER      res_partner (+ res_partner_bank), res_bank_account (bank & kas operasional),
--               location, product, vehicle, pricelist_item, route_sla
--   OPERASIONAL job, trip_update
--   KEUANGAN    job_line            rencana uang job (selling, cost truk, calo, tol, ...)
--               account_move        invoice customer (out_invoice) / pengajuan bayar vendor (in_invoice)
--               account_move_line   isi dokumen, 1 baris = 1 baris order job
--               account_payment     uang benar-benar masuk / keluar rekening (batal = pembalik minus)
--               account_payment_line
--               internal_transfer   pindah uang antar rekening sendiri (transfer malam ke kas operasional)
--
-- Semua saldo (sisa tagih, utang, piutang, kurang transfer, titipan operasional) = VIEW (002_views.sql).
-- Kolom legacy_* = asal data saat dipindah dari ERP AMICO lama (Supabase).
-- ============================================================================

-- ---------------------------------------------------------------- akses
create table app_user (
  id integer generated by default as identity primary key,
  username text not null unique check (username ~ '^[a-z0-9._-]{3,40}$'),
  display_name text not null,
  email text,
  role text not null check (role in ('ADMIN', 'OPERATIONAL', 'FINANCE', 'VIEWER')),
  password_hash text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  last_login_at timestamptz
);

create table app_session (
  token text primary key,
  user_id integer not null references app_user(id) on delete cascade,
  created_at timestamptz not null default now(),
  expires_at timestamptz not null
);
create index app_session_user_idx on app_session (user_id);

create table audit_log (
  id integer generated by default as identity primary key,
  at timestamptz not null default now(),
  user_id integer references app_user(id),
  entity text not null,          -- job, job_line, account_move, account_payment, ...
  entity_id integer,
  action text not null,          -- create, update, post, approve, cancel, pay, reverse, topup, ...
  detail jsonb
);
create index audit_log_entity_idx on audit_log (entity, entity_id);

