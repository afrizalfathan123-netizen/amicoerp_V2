create table vehicle (
  id integer generated by default as identity primary key,
  plate_number text not null unique,
  truck_type text not null,
  owner_partner_id integer references res_partner(id),   -- vendor pemilik unit
  pic text,
  active boolean not null default true,
  legacy_id uuid
);

-- Price book. customer_id kosong = harga umum. selling / cost boleh salah satu saja.
create table pricelist_item (
  id integer generated by default as identity primary key,
  customer_id integer references res_partner(id),
  pol_id integer not null references location(id),
  pod_id integer not null references location(id),
  truck_type text not null,
  trip_type text not null check (trip_type in ('ONE_WAY', 'ROUND_TRIP')),
  selling numeric(15, 2) check (selling is null or selling >= 0),
  cost numeric(15, 2) check (cost is null or cost >= 0),
  effective_from date,
  effective_to date,
  active boolean not null default true
);
create index pricelist_lookup_idx on pricelist_item (pol_id, pod_id, truck_type, trip_type);

-- Batas waktu perjalanan per rute (untuk tracker).
create table route_sla (
  id integer generated by default as identity primary key,
  pol_id integer not null references location(id),
  pod_id integer not null references location(id),
  trip_type text not null default 'ONE_WAY' check (trip_type in ('ONE_WAY', 'ROUND_TRIP')),
  sla_hours numeric(6, 1) not null check (sla_hours > 0),
  unique (pol_id, pod_id, trip_type)
);

-- ---------------------------------------------------------------- operasional
create table job (
  id integer generated by default as identity primary key,
  job_number text not null unique,
  job_date date not null,
  customer_id integer not null references res_partner(id),
  vendor_id integer references res_partner(id),
  pol_id integer not null references location(id),
  pod_id integer not null references location(id),
  trip_type text not null default 'ONE_WAY' check (trip_type in ('ONE_WAY', 'ROUND_TRIP')),
  service_type text not null default 'TRUCKING' check (service_type in ('TRUCKING', 'FORWARDING')),
  delivery_scope text not null default 'INTERCITY' check (delivery_scope in ('INTERCITY', 'INNERCITY')),
  rit_number integer check (rit_number is null or rit_number >= 1),
  truck_type text not null,
  vehicle_id integer references vehicle(id),
  plate_number text,
  driver1_name text,
  driver1_phone text,
  driver2_name text,
  driver2_phone text,
  do_number text,                -- DO / kode tugas
  -- keuangan job
  payment_scheme text not null default '70_30' check (payment_scheme in ('70_30', 'FULL')),
  selling_mode text not null default 'PRICE_BOOK' check (selling_mode in ('PRICE_BOOK', 'CUSTOM', 'ZERO')),
  selling_after_tax numeric(15, 2),   -- isi hanya kalau beda dari hitungan pajak customer
  state text not null default 'confirmed' check (state in ('confirmed', 'done', 'cancelled')),
  -- perjalanan & surat jalan
  gate_out_at timestamptz,
  gate_in_at timestamptz,
  sj_number text,
  sj_resi_received_at date,
  sj_received_at date,
  sj_resi_number text,
  sj_delivered_at date,
  sj_delivered_resi_number text,
  note text,
  source text not null default 'APP' check (source in ('APP', 'AMICO', 'JOB_REG')),
  legacy_id uuid,
  created_by integer references app_user(id),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index job_date_idx on job (job_date);
create index job_plate_idx on job (plate_number);
create index job_customer_idx on job (customer_id);

-- Update posisi perjalanan (tracker)
create table trip_update (
  id integer generated by default as identity primary key,
  job_id integer not null references job(id) on delete cascade,
  at timestamptz not null default now(),
  location text not null,
  note text,
  created_by integer references app_user(id)
);
create index trip_update_job_idx on trip_update (job_id, at desc);

-- ---------------------------------------------------------------- keuangan
create table job_line (
  id integer generated by default as identity primary key,
  job_id integer not null references job(id) on delete cascade,
  side text not null check (side in ('SALE', 'PURCHASE')),
  product_id integer not null references product(id),
  partner_id integer references res_partner(id),            -- SALE: customer, PURCHASE: yang dibayar
  partner_bank_id integer references res_partner_bank(id),  -- rekening tujuan (vendor / calo)
  description text,
  amount numeric(15, 2) not null default 0 check (amount >= 0),
  legacy_key text,
  created_at timestamptz not null default now()
);
create index job_line_job_idx on job_line (job_id);

create table account_move (
  id integer generated by default as identity primary key,
  number text unique,                                   -- diisi saat posting
  move_type text not null check (move_type in ('out_invoice', 'in_invoice')),
  phase text not null check (phase in ('DP_70', 'SETTLEMENT_30', 'FULL', 'OTHER')),
  partner_id integer references res_partner(id),        -- out_invoice: customer (wajib); in_invoice: boleh kosong (batch banyak vendor)
  move_date date not null,
  due_date date,
  bank_account_id integer references res_bank_account(id),   -- out_invoice: rekening tujuan transfer customer
  state text not null default 'draft' check (state in ('draft', 'posted', 'cancelled')),
  approval_state text not null default 'NOT_REQUIRED' check (approval_state in ('NOT_REQUIRED', 'PENDING', 'APPROVED', 'REJECTED')),
  payment_channel text not null default 'NORMAL' check (payment_channel in ('NORMAL', 'TRANSFER_MALAM')),
  tax_basis numeric(15, 2) not null default 0,          -- info pajak untuk cetak invoice
  ppn_amount numeric(15, 2) not null default 0,
  pph23_amount numeric(15, 2) not null default 0,
  bill_to_name text,
  bill_to_address text,
  bill_to_npwp text,
  note text,
  cancel_reason text,
  rejection_reason text,
  legacy_source text,
  legacy_id uuid,
  legacy_number text,
  created_by integer references app_user(id),
  created_at timestamptz not null default now(),
  posted_at timestamptz,
  approved_by integer references app_user(id),
  approved_at timestamptz,
  cancelled_at timestamptz,
  check (move_type <> 'out_invoice' or partner_id is not null)
);
create index account_move_type_state_idx on account_move (move_type, state);

create table account_move_line (
  id integer generated by default as identity primary key,
  move_id integer not null references account_move(id) on delete cascade,
  line_no integer not null default 0,
  job_line_id integer not null references job_line(id),
  job_id integer not null references job(id),
  amount numeric(15, 2) not null check (amount > 0),
  description text,
  payee_partner_id integer references res_partner(id),  -- penerima transfer (pengajuan vendor)
  payee_bank_name text,
  payee_account_number text,
  payee_holder text,
  cancelled_at timestamptz,                             -- baris batal (mis. di-refund): tidak dihitung lagi
  cancel_reason text,
  legacy_item_id uuid
);
create index account_move_line_move_idx on account_move_line (move_id);
create index account_move_line_job_line_idx on account_move_line (job_line_id);
create index account_move_line_job_idx on account_move_line (job_id);

create table account_payment (
  id integer generated by default as identity primary key,
  number text not null unique,
  payment_type text not null check (payment_type in ('inbound', 'outbound')),
  move_id integer not null references account_move(id),
  pay_date date not null,
  amount numeric(15, 2) not null,                       -- minus kalau pembalik
  bank_account_id integer references res_bank_account(id),   -- rekening AMICO yang dipakai (kas operasional untuk transfer malam)
  reversed_payment_id integer references account_payment(id),
  state text not null default 'posted' check (state in ('posted', 'reversed')),
  proof_url text,
  note text,
  legacy_source text,
  legacy_id uuid,
  created_by integer references app_user(id),
  created_at timestamptz not null default now()
);
create index account_payment_move_idx on account_payment (move_id);
create index account_payment_bank_idx on account_payment (bank_account_id);

create table account_payment_line (
  id integer generated by default as identity primary key,
  payment_id integer not null references account_payment(id) on delete cascade,
  move_line_id integer not null references account_move_line(id),
  job_id integer not null references job(id),
  amount numeric(15, 2) not null,
  actual_payee_name text,                               -- penerima sebenarnya kalau beda (ganti rekening, dll)
  actual_bank_name text,
  actual_account_number text,
  actual_holder text
);
create index account_payment_line_move_line_idx on account_payment_line (move_line_id);
create index account_payment_line_payment_idx on account_payment_line (payment_id);
create index account_payment_line_job_idx on account_payment_line (job_id);

-- Pindah uang antar rekening AMICO. Transfer malam: rekening BANK -> kas OPERATIONAL (dana untuk satu pengajuan),
-- lalu operasional menyalurkan ke vendor = account_payment dari kas operasional. Uang kembali = transfer balik.
create table internal_transfer (
  id integer generated by default as identity primary key,
  number text not null unique,
  transfer_date date not null,
  from_account_id integer not null references res_bank_account(id),
  to_account_id integer not null references res_bank_account(id),
  amount numeric(15, 2) not null check (amount > 0),
  move_id integer references account_move(id),          -- pengajuan yang didanai (transfer malam)
  note text,
  legacy_source text,
  legacy_id uuid,
  created_by integer references app_user(id),
  created_at timestamptz not null default now(),
  check (from_account_id <> to_account_id)
);
create index internal_transfer_move_idx on internal_transfer (move_id);
