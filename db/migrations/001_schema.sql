-- ---------------------------------------------------------------- master
-- Customer, vendor, calo dalam satu tabel (res.partner). Pajak customer: selling setelah pajak = selling x (1 - PPh% + PPN%).
create table res_partner (
  id integer generated by default as identity primary key,
  code text not null unique,
  name text not null,
  is_customer boolean not null default false,
  is_vendor boolean not null default false,
  phone text,
  email text,
  address text,
  npwp text,
  bill_to_name text,             -- nama / alamat / NPWP di invoice kalau beda dengan data partner
  bill_to_address text,
  bill_to_npwp text,
  pph_pct numeric(5, 2) not null default 0 check (pph_pct >= 0),
  ppn_pct numeric(5, 2) not null default 0 check (ppn_pct >= 0),
  payment_terms_days integer not null default 0,
  active boolean not null default true,
  legacy_id uuid,
  created_at timestamptz not null default now()
);

-- Rekening penerima transfer milik partner (vendor / calo / driver). Pengganti transfer_payees.
create table res_partner_bank (
  id integer generated by default as identity primary key,
  partner_id integer not null references res_partner(id) on delete cascade,
  bank_name text not null,
  account_number text not null,
  holder text not null,
  is_default boolean not null default false,
  active boolean not null default true,
  legacy_id uuid,
  unique (partner_id, bank_name, account_number)
);

-- Rekening milik AMICO. kind OPERATIONAL = kas / rekening operasional (perantara transfer malam).
create table res_bank_account (
  id integer generated by default as identity primary key,
  name text not null,
  bank_name text not null,
  account_number text not null,
  holder text not null,
  kind text not null default 'BANK' check (kind in ('BANK', 'OPERATIONAL')),
  for_tax_invoice boolean not null default false,
  is_default boolean not null default false,
  active boolean not null default true,
  legacy_id uuid
);

create table location (
  id integer generated by default as identity primary key,
  code text not null unique,
  name text not null,
  province text,
  active boolean not null default true
);

create table product (
  id integer generated by default as identity primary key,
  code text not null unique,
  name text not null,
  kind text not null unique check (kind in ('TRUCKING', 'CALO', 'TOL', 'PARKIR', 'BONGKAR', 'LAINNYA', 'SELISIH'))
);
